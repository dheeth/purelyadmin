fun copyToClipboard(context: Context, label: String, text: String) {
    val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
    val clip = ClipData.newPlainText(label, text)
    clipboard.setPrimaryClip(clip)
    Toast.makeText(context, "$label copied to clipboard", Toast.LENGTH_SHORT).show()
}

@Composable
fun DnsBadgeRow(
    dnsSummary: ApiDomainDnsSummary,
    modifier: Modifier = Modifier
) {
    Row(
        modifier = modifier,
        horizontalArrangement = Arrangement.spacedBy(6.dp),
        verticalAlignment = Alignment.CenterVertically
    ) {
        DnsBadgeChip(name = "MX", passes = dnsSummary.passesMx)
        DnsBadgeChip(name = "SPF", passes = dnsSummary.passesSpf)
        DnsBadgeChip(name = "DKIM", passes = dnsSummary.passesDkim)
        DnsBadgeChip(name = "DMARC", passes = dnsSummary.passesDmarc)
    }
}

@Composable
fun DnsBadgeChip(
    name: String,
    passes: Boolean,
    modifier: Modifier = Modifier
) {
    val bgColor = if (passes) StatusSuccess.copy(alpha = 0.15f) else StatusError.copy(alpha = 0.15f)
    val contentColor = if (passes) StatusSuccess else StatusError
    val icon = if (passes) Icons.Default.CheckCircle else Icons.Default.Cancel

    Surface(
        color = bgColor,
        contentColor = contentColor,
        shape = RoundedCornerShape(8.dp),
        modifier = modifier
    ) {
        Row(
            modifier = Modifier.padding(horizontal = 6.dp, vertical = 3.dp),
            verticalAlignment = Alignment.CenterVertically,
            horizontalArrangement = Arrangement.spacedBy(3.dp)
        ) {
            Icon(
                imageVector = icon,
                contentDescription = null,
                modifier = Modifier.size(12.dp)
            )
            Text(
                text = name,
                fontSize = 11.sp,
                fontWeight = FontWeight.Bold,
                fontFamily = FontFamily.Monospace
            )
        }
    }
}

@Composable
